
create table if not exists public.skill_categories (
  id bigint generated by default as identity primary key,
  parent_id bigint references public.skill_categories(id) on delete restrict,
  slug text not null unique,
  name text not null,
  description text,
  created_at timestamptz not null default now()
);

create table if not exists public.skill_sources (
  id bigint generated by default as identity primary key,
  source_type text not null check (source_type in ('github','chatgpt_plugin','mcp','internal','documentation','other')),
  name text not null,
  uri text,
  repository text,
  owner text,
  license text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.skill_tools (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  tool_type text not null check (tool_type in ('mcp','api','cli','library','connector','browser','other')),
  description text,
  endpoint text,
  documentation_uri text,
  configuration_schema jsonb not null default '{}'::jsonb,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.skill_capabilities (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  description text,
  created_at timestamptz not null default now()
);

alter table public.skills
  add column if not exists slug text,
  add column if not exists description text,
  add column if not exists category_id bigint references public.skill_categories(id) on delete set null,
  add column if not exists source_id bigint references public.skill_sources(id) on delete set null,
  add column if not exists status text not null default 'active'
    check (status in ('draft','active','deprecated','archived')),
  add column if not exists metadata jsonb not null default '{}'::jsonb,
  add column if not exists updated_at timestamptz not null default now();

update public.skills
set slug = lower(regexp_replace(name, '[^a-zA-Z0-9]+', '-', 'g'))
where slug is null;

alter table public.skills alter column slug set not null;
create unique index if not exists skills_slug_uidx on public.skills(slug);

create table if not exists public.skill_versions (
  id uuid primary key default gen_random_uuid(),
  skill_id bigint not null references public.skills(id) on delete cascade,
  version text not null,
  instructions text not null,
  manifest jsonb not null default '{}'::jsonb,
  changelog text,
  is_published boolean not null default false,
  created_at timestamptz not null default now(),
  published_at timestamptz,
  unique(skill_id, version)
);

alter table public.skills
  add column if not exists current_version_id uuid
  references public.skill_versions(id) on delete set null;

insert into public.skill_versions (skill_id, version, instructions, manifest, is_published, published_at)
select s.id, '1.0.0', s.instructions,
       jsonb_build_object('id', s.slug, 'name', s.name, 'version', '1.0.0'),
       true, now()
from public.skills s
where not exists (
  select 1 from public.skill_versions v where v.skill_id = s.id
);

update public.skills s
set current_version_id = v.id
from public.skill_versions v
where v.skill_id = s.id and s.current_version_id is null and v.version = '1.0.0';

create table if not exists public.skill_capability_links (
  skill_id bigint not null references public.skills(id) on delete cascade,
  capability_id bigint not null references public.skill_capabilities(id) on delete cascade,
  primary key (skill_id, capability_id)
);

create table if not exists public.skill_dependencies (
  skill_id bigint not null references public.skills(id) on delete cascade,
  depends_on_skill_id bigint not null references public.skills(id) on delete restrict,
  dependency_type text not null default 'required'
    check (dependency_type in ('required','optional','recommended')),
  version_constraint text,
  created_at timestamptz not null default now(),
  primary key (skill_id, depends_on_skill_id),
  check (skill_id <> depends_on_skill_id)
);

create table if not exists public.skill_tool_links (
  skill_id bigint not null references public.skills(id) on delete cascade,
  tool_id bigint not null references public.skill_tools(id) on delete cascade,
  usage text,
  is_required boolean not null default true,
  primary key (skill_id, tool_id)
);

create table if not exists public.skill_resources (
  id bigint generated by default as identity primary key,
  skill_id bigint not null references public.skills(id) on delete cascade,
  resource_type text not null check (resource_type in ('documentation','repository','example','tutorial','specification','test','other')),
  title text not null,
  uri text not null,
  description text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.skill_triggers (
  id bigint generated by default as identity primary key,
  skill_id bigint not null references public.skills(id) on delete cascade,
  trigger_type text not null check (trigger_type in ('exact','phrase','keyword','semantic','intent')),
  value text not null,
  weight numeric(5,4) not null default 1.0 check (weight >= 0 and weight <= 1),
  created_at timestamptz not null default now(),
  unique(skill_id, trigger_type, value)
);

create table if not exists public.skill_evaluations (
  id bigint generated by default as identity primary key,
  skill_id bigint not null references public.skills(id) on delete cascade,
  version_id uuid references public.skill_versions(id) on delete set null,
  evaluator text not null,
  test_name text not null,
  score numeric(6,5) check (score >= 0 and score <= 1),
  passed boolean,
  details jsonb not null default '{}'::jsonb,
  evaluated_at timestamptz not null default now()
);

create index if not exists skills_category_idx on public.skills(category_id);
create index if not exists skills_source_idx on public.skills(source_id);
create index if not exists skill_versions_skill_idx on public.skill_versions(skill_id, created_at desc);
create index if not exists skill_dependencies_target_idx on public.skill_dependencies(depends_on_skill_id);
create index if not exists skill_resources_skill_idx on public.skill_resources(skill_id);
create index if not exists skill_triggers_value_idx on public.skill_triggers using gin (to_tsvector('simple', value));
create index if not exists skills_search_idx on public.skills using gin (
  to_tsvector('simple', coalesce(name,'') || ' ' || coalesce(description,'') || ' ' || coalesce(instructions,''))
);

