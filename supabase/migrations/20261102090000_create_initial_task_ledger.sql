-- Original task ledger foundation. These objects predate the first tracked
-- task-ledger migration and were previously provisioned manually in Supabase.
-- Keep this baseline before 20261102092012_formalize_task_contracts_and_agent_coordination.sql.

create table if not exists public.tasks (
  id uuid primary key default gen_random_uuid(),
  task_key text not null unique default ('task_' || replace(gen_random_uuid()::text,'-','')),
  agent_id text not null,
  agent_name text not null,
  agent_type text,
  session_id text,
  task_name text not null,
  description text,
  status text not null default 'queued'
    check (status in ('queued','running','blocked','waiting','completed','failed','cancelled','abandoned')),
  tags text[] not null default '{}'::text[],
  priority smallint not null default 3 check (priority between 1 and 5),
  started_at timestamptz not null default now(),
  heartbeat_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  completed_at timestamptz,
  due_at timestamptz,
  parent_task_id uuid references public.tasks(id) on delete set null,
  context_summary text,
  current_step text,
  blocker text,
  outcome text,
  metadata jsonb not null default '{}'::jsonb
);

create table if not exists public.task_events (
  id bigint generated by default as identity primary key,
  task_id uuid not null references public.tasks(id) on delete cascade,
  event_type text not null,
  agent_id text not null,
  occurred_at timestamptz not null default now(),
  message text,
  payload jsonb not null default '{}'::jsonb
);

create index if not exists tasks_agent_status_idx on public.tasks(agent_id,status,heartbeat_at desc);
create index if not exists tasks_started_at_idx on public.tasks(started_at desc);
create index if not exists tasks_status_heartbeat_idx on public.tasks(status,heartbeat_at desc);
create index if not exists tasks_tags_gin_idx on public.tasks using gin(tags);
create index if not exists task_events_task_time_idx on public.task_events(task_id,occurred_at desc);
create index if not exists task_events_time_idx on public.task_events(occurred_at desc);

alter table public.tasks enable row level security;
alter table public.task_events enable row level security;

create or replace view public.active_tasks with (security_invoker=true) as
select
  id,task_key,agent_id,agent_name,agent_type,session_id,task_name,description,
  status,tags,priority,started_at,heartbeat_at,updated_at,completed_at,due_at,
  parent_task_id,context_summary,current_step,blocker,outcome,metadata,
  now()-heartbeat_at as heartbeat_age,
  case
    when heartbeat_at < now()-interval '7 days' then 'stale_over_7_days'
    when heartbeat_at < now()-interval '1 day' then 'stale_over_1_day'
    when heartbeat_at < now()-interval '1 hour' then 'stale_over_1_hour'
    else 'recent'
  end as freshness
from public.tasks
where status in ('queued','running','blocked','waiting');

create or replace function public.task_ledger_register(
  agent_id_in text,
  agent_name_in text,
  task_name_in text,
  description_in text default null,
  tags_in text[] default '{}'::text[],
  session_id_in text default null,
  agent_type_in text default null,
  priority_in smallint default 3,
  context_summary_in text default null,
  metadata_in jsonb default '{}'::jsonb,
  parent_task_id_in uuid default null
)
returns public.tasks
language plpgsql
set search_path to 'public'
as $function$
declare
  task_out public.tasks;
begin
  insert into public.tasks(
    agent_id,agent_name,task_name,description,tags,session_id,agent_type,
    priority,context_summary,metadata,parent_task_id
  )
  values(
    agent_id_in,agent_name_in,task_name_in,description_in,coalesce(tags_in,'{}'),
    session_id_in,agent_type_in,coalesce(priority_in,3),context_summary_in,
    coalesce(metadata_in,'{}'::jsonb),parent_task_id_in
  )
  returning * into task_out;

  insert into public.task_events(task_id,event_type,agent_id,message,payload)
  values(
    task_out.id,'registered',agent_id_in,task_name_in,
    jsonb_build_object('agent_name',agent_name_in,'tags',coalesce(tags_in,'{}'))
  );
  return task_out;
end;
$function$;

create or replace function public.task_ledger_heartbeat(
  task_id_in uuid,
  agent_id_in text,
  current_step_in text default null,
  context_summary_in text default null,
  metadata_patch_in jsonb default '{}'::jsonb
)
returns public.tasks
language plpgsql
set search_path to 'public'
as $function$
declare
  task_out public.tasks;
begin
  update public.tasks
  set heartbeat_at=now(),
      updated_at=now(),
      current_step=coalesce(current_step_in,current_step),
      context_summary=coalesce(context_summary_in,context_summary),
      metadata=metadata||coalesce(metadata_patch_in,'{}'::jsonb)
  where id=task_id_in
    and agent_id=agent_id_in
    and status in ('running','blocked','waiting')
  returning * into task_out;

  if task_out.id is null then
    raise exception 'Task not found, not owned by agent, or not active';
  end if;

  insert into public.task_events(task_id,event_type,agent_id,message)
  values(task_out.id,'heartbeat',agent_id_in,current_step_in);
  return task_out;
end;
$function$;

create or replace function public.task_ledger_update(
  task_id_in uuid,
  agent_id_in text,
  status_in text default null,
  current_step_in text default null,
  context_summary_in text default null,
  blocker_in text default null,
  outcome_in text default null,
  tags_in text[] default null,
  message_in text default null,
  metadata_patch_in jsonb default '{}'::jsonb
)
returns public.tasks
language plpgsql
set search_path to 'public'
as $function$
declare
  task_out public.tasks;
  event_out text;
begin
  if status_in is not null and status_in not in
    ('queued','running','blocked','waiting','completed','failed','cancelled','abandoned') then
    raise exception 'Invalid task status: %',status_in;
  end if;

  update public.tasks
  set status=coalesce(status_in,status),
      heartbeat_at=now(),
      updated_at=now(),
      completed_at=case
        when status_in in ('completed','failed','cancelled','abandoned') then now()
        when status_in in ('running','blocked','waiting','queued') then null
        else completed_at
      end,
      current_step=coalesce(current_step_in,current_step),
      context_summary=coalesce(context_summary_in,context_summary),
      blocker=coalesce(blocker_in,blocker),
      outcome=coalesce(outcome_in,outcome),
      tags=coalesce(tags_in,tags),
      metadata=metadata||coalesce(metadata_patch_in,'{}'::jsonb)
  where id=task_id_in and agent_id=agent_id_in
  returning * into task_out;

  if task_out.id is null then
    raise exception 'Task not found or not owned by agent';
  end if;

  event_out:=case
    when status_in='completed' then 'completed'
    when status_in='failed' then 'failed'
    when status_in='cancelled' then 'cancelled'
    when status_in='abandoned' then 'abandoned'
    when status_in='blocked' then 'blocked'
    when status_in='running' then 'unblocked'
    when tags_in is not null then 'tagged'
    else 'progress'
  end;

  insert into public.task_events(task_id,event_type,agent_id,message,payload)
  values(
    task_out.id,event_out,agent_id_in,message_in,
    jsonb_build_object(
      'status',task_out.status,'current_step',task_out.current_step,
      'tags',task_out.tags,'blocker',task_out.blocker,'outcome',task_out.outcome
    )
  );
  return task_out;
end;
$function$;

