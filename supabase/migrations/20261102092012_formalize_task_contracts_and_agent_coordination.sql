CREATE TABLE IF NOT EXISTS public.task_dependencies (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id uuid NOT NULL REFERENCES public.tasks(id) ON DELETE CASCADE,
  depends_on_task_id uuid NOT NULL REFERENCES public.tasks(id) ON DELETE CASCADE,
  dependency_type text NOT NULL DEFAULT 'blocking' CHECK (dependency_type IN ('blocking','advisory')),
  created_by_agent_id text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT task_dependencies_not_self CHECK (task_id <> depends_on_task_id),
  CONSTRAINT task_dependencies_unique UNIQUE (task_id,depends_on_task_id)
);

CREATE TABLE IF NOT EXISTS public.task_iterations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id uuid NOT NULL REFERENCES public.tasks(id) ON DELETE CASCADE,
  iteration_no integer NOT NULL CHECK (iteration_no > 0),
  agent_id text NOT NULL,
  status text NOT NULL DEFAULT 'completed' CHECK (status IN ('started','completed','failed','skipped')),
  input_payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  output_payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  observation jsonb NOT NULL DEFAULT '{}'::jsonb,
  decision text,
  tools_used jsonb NOT NULL DEFAULT '[]'::jsonb,
  evidence jsonb NOT NULL DEFAULT '[]'::jsonb,
  started_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz,
  CONSTRAINT task_iterations_unique UNIQUE (task_id,iteration_no)
);

