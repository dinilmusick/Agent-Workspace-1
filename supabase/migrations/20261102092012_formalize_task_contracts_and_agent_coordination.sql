CREATE OR REPLACE FUNCTION public.task_ledger_create_tree(
  agent_id_in text, agent_name_in text, task_definition_in jsonb,
  parent_task_id_in uuid DEFAULT NULL, session_id_in text DEFAULT NULL, agent_type_in text DEFAULT NULL
) RETURNS uuid LANGUAGE plpgsql SET search_path = public AS $$
DECLARE
  task_id_out uuid;
  child_definition jsonb;
  priority_value smallint;
BEGIN
  IF nullif(btrim(agent_id_in),'') IS NULL OR nullif(btrim(agent_name_in),'') IS NULL THEN
    RAISE EXCEPTION 'agent_id and agent_name are required';
  END IF;
  IF jsonb_typeof(task_definition_in) <> 'object' OR nullif(btrim(task_definition_in->>'name'),'') IS NULL THEN
    RAISE EXCEPTION 'task_definition must be an object with a non-empty name';
  END IF;
  priority_value := coalesce((task_definition_in->>'priority')::smallint,3);
  IF priority_value < 1 OR priority_value > 5 THEN RAISE EXCEPTION 'priority must be between 1 and 5'; END IF;
  IF parent_task_id_in IS NOT NULL AND NOT EXISTS (SELECT 1 FROM public.tasks WHERE id=parent_task_id_in) THEN
    RAISE EXCEPTION 'parent task not found';
  END IF;
  IF jsonb_typeof(coalesce(task_definition_in->'subtasks','[]'::jsonb)) <> 'array' THEN
    RAISE EXCEPTION 'subtasks must be a JSON array';
  END IF;

  INSERT INTO public.tasks(
    agent_id,agent_name,agent_type,session_id,task_name,description,status,tags,priority,
    parent_task_id,context_summary,metadata,due_at,task_definition,input_contract,
    output_contract,acceptance_criteria,verification_plan,loop_definition,required_tools,
    required_capabilities,max_attempts
  ) VALUES (
    agent_id_in,agent_name_in,agent_type_in,session_id_in,task_definition_in->>'name',
    task_definition_in->>'description','queued',
    ARRAY(SELECT jsonb_array_elements_text(coalesce(task_definition_in->'tags','[]'::jsonb))),
    priority_value,parent_task_id_in,task_definition_in->>'context_summary',
    coalesce(task_definition_in->'metadata','{}'::jsonb),
    nullif(task_definition_in->>'due_at','')::timestamptz,
    task_definition_in,coalesce(task_definition_in->'inputs','{}'::jsonb),
    coalesce(task_definition_in->'outputs','{}'::jsonb),
    coalesce(task_definition_in->'acceptance_criteria','[]'::jsonb),
    coalesce(task_definition_in->'verification','{}'::jsonb),
    coalesce(task_definition_in->'loop','{}'::jsonb),
    coalesce(task_definition_in->'required_tools','[]'::jsonb),
    ARRAY(SELECT jsonb_array_elements_text(coalesce(task_definition_in->'required_capabilities','[]'::jsonb))),
    greatest(1,coalesce((task_definition_in->>'max_attempts')::integer,3))
  ) RETURNING id INTO task_id_out;

  INSERT INTO public.task_events(task_id,event_type,agent_id,message,payload)
  VALUES(task_id_out,'registered',agent_id_in,task_definition_in->>'name',
    jsonb_build_object('parent_task_id',parent_task_id_in,'definition',task_definition_in));

  FOR child_definition IN SELECT value FROM jsonb_array_elements(coalesce(task_definition_in->'subtasks','[]'::jsonb))
  LOOP
    PERFORM public.task_ledger_create_tree(agent_id_in,agent_name_in,child_definition,task_id_out,session_id_in,agent_type_in);
  END LOOP;

  IF jsonb_array_length(coalesce(task_definition_in->'subtasks','[]'::jsonb)) > 0 THEN
    INSERT INTO public.task_events(task_id,event_type,agent_id,message,payload)
    VALUES(task_id_out,'tree_created',agent_id_in,'Nested task tree created',
      jsonb_build_object('direct_subtask_count',jsonb_array_length(task_definition_in->'subtasks')));
  END IF;
  RETURN task_id_out;
END;
$$;

CREATE OR REPLACE FUNCTION public.task_ledger_claim_next(
  agent_id_in text, agent_name_in text, agent_type_in text DEFAULT 'worker',
  capabilities_in text[] DEFAULT '{}'::text[], lease_seconds_in integer DEFAULT 900
) RETURNS SETOF public.tasks LANGUAGE plpgsql SET search_path = public AS $$
DECLARE
  candidate_id uuid;
  task_out public.tasks;
  lease_value integer := greatest(30,least(coalesce(lease_seconds_in,900),86400));
BEGIN
  IF nullif(btrim(agent_id_in),'') IS NULL OR nullif(btrim(agent_name_in),'') IS NULL THEN
    RAISE EXCEPTION 'agent identity is required';
  END IF;
  SELECT t.id INTO candidate_id
  FROM public.tasks t
  WHERE t.status IN ('queued','running') AND t.attempt_count < t.max_attempts
    AND (t.claim_expires_at IS NULL OR t.claim_expires_at < now())
    AND t.required_capabilities <@ coalesce(capabilities_in,'{}'::text[])
    AND (t.parent_task_id IS NULL OR NOT EXISTS (
      SELECT 1 FROM public.tasks p WHERE p.id=t.parent_task_id AND p.status IN ('failed','cancelled','abandoned')
    ))
    AND NOT EXISTS (
      SELECT 1 FROM public.task_dependencies d JOIN public.tasks dep ON dep.id=d.depends_on_task_id
      WHERE d.task_id=t.id AND d.dependency_type='blocking'
        AND (dep.status <> 'completed' OR dep.verification_status <> 'verified')
    )
  ORDER BY t.priority ASC,t.started_at ASC
  FOR UPDATE SKIP LOCKED LIMIT 1;
  IF candidate_id IS NULL THEN RETURN; END IF;

  UPDATE public.tasks
  SET status='running',claimed_by_agent_id=agent_id_in,claimed_by_agent_name=agent_name_in,
      claim_token=gen_random_uuid(),claimed_at=now(),claim_expires_at=now()+make_interval(secs=>lease_value),
      attempt_count=attempt_count+1,heartbeat_at=now(),updated_at=now(),current_step='Claimed by worker agent'
  WHERE id=candidate_id RETURNING * INTO task_out;

  INSERT INTO public.task_events(task_id,event_type,agent_id,message,payload)
  VALUES(task_out.id,'claimed',agent_id_in,'Task claimed by worker',
    jsonb_build_object('lease_expires_at',task_out.claim_expires_at,'attempt_count',task_out.attempt_count));
  RETURN NEXT task_out;
END;
$$;

CREATE OR REPLACE FUNCTION public.task_ledger_heartbeat_claim(
  task_id_in uuid, agent_id_in text, claim_token_in uuid,
  current_step_in text DEFAULT NULL, lease_seconds_in integer DEFAULT 900
) RETURNS public.tasks LANGUAGE plpgsql SET search_path = public AS $$
DECLARE task_out public.tasks;
BEGIN
  UPDATE public.tasks
  SET heartbeat_at=now(),updated_at=now(),current_step=coalesce(current_step_in,current_step),
      claim_expires_at=now()+make_interval(secs=>greatest(30,least(coalesce(lease_seconds_in,900),86400)))
  WHERE id=task_id_in AND claimed_by_agent_id=agent_id_in AND claim_token=claim_token_in AND status='running'
  RETURNING * INTO task_out;
  IF task_out.id IS NULL THEN RAISE EXCEPTION 'Claim not found, expired, or not owned by agent'; END IF;
  INSERT INTO public.task_events(task_id,event_type,agent_id,message)
  VALUES(task_id_in,'heartbeat',agent_id_in,current_step_in);
  RETURN task_out;
END;
$$;

CREATE OR REPLACE FUNCTION public.task_ledger_submit_result(
  task_id_in uuid, agent_id_in text, claim_token_in uuid, result_in jsonb,
  result_summary_in text DEFAULT NULL, tools_used_in jsonb DEFAULT '[]'::jsonb,
  evidence_in jsonb DEFAULT '[]'::jsonb, status_in text DEFAULT 'completed'
) RETURNS public.tasks LANGUAGE plpgsql SET search_path = public AS $$
DECLARE task_out public.tasks;
BEGIN
  IF status_in NOT IN ('completed','failed','blocked','waiting') THEN
    RAISE EXCEPTION 'result status must be completed, failed, blocked, or waiting';
  END IF;
  UPDATE public.tasks
  SET result=coalesce(result_in,'{}'::jsonb),result_summary=result_summary_in,
      tools_used=coalesce(tools_used_in,'[]'::jsonb),evidence=coalesce(evidence_in,'[]'::jsonb),
      result_submitted_at=now(),status=status_in,
      verification_status=CASE WHEN status_in='completed' THEN 'pending' ELSE 'not_started' END,
      outcome=result_summary_in,heartbeat_at=now(),updated_at=now(),
      completed_at=CASE WHEN status_in='completed' THEN now() ELSE NULL END,
      claim_expires_at=NULL,claim_token=NULL
  WHERE id=task_id_in AND claimed_by_agent_id=agent_id_in AND claim_token=claim_token_in AND status='running'
  RETURNING * INTO task_out;
  IF task_out.id IS NULL THEN RAISE EXCEPTION 'Task claim not found or not owned by submitting agent'; END IF;
  INSERT INTO public.task_events(task_id,event_type,agent_id,message,payload)
  VALUES(task_id_in,'result_submitted',agent_id_in,result_summary_in,
    jsonb_build_object('status',status_in,'result',coalesce(result_in,'{}'::jsonb),
      'tools_used',coalesce(tools_used_in,'[]'::jsonb),'evidence',coalesce(evidence_in,'[]'::jsonb)));
  RETURN task_out;
END;
$$;

CREATE OR REPLACE FUNCTION public.task_ledger_verify_result(
  task_id_in uuid, verifier_agent_id_in text, verified_in boolean, verification_report_in jsonb
) RETURNS public.tasks LANGUAGE plpgsql SET search_path = public AS $$
DECLARE task_out public.tasks;
BEGIN
  UPDATE public.tasks t
  SET verification_status=CASE WHEN verified_in THEN 'verified' ELSE 'rejected' END,
      verification_report=coalesce(verification_report_in,'{}'::jsonb),
      verified_by_agent_id=verifier_agent_id_in,verified_at=now(),
      status=CASE WHEN verified_in THEN 'completed' ELSE 'queued' END,
      completed_at=CASE WHEN verified_in THEN now() ELSE NULL END,
      claimed_by_agent_id=CASE WHEN verified_in THEN claimed_by_agent_id ELSE NULL END,
      claimed_by_agent_name=CASE WHEN verified_in THEN claimed_by_agent_name ELSE NULL END,
      claim_token=CASE WHEN verified_in THEN claim_token ELSE NULL END,
      claim_expires_at=CASE WHEN verified_in THEN claim_expires_at ELSE NULL END,
      updated_at=now()
  WHERE t.id=task_id_in AND t.status='completed' AND t.verification_status='pending'
    AND (t.agent_id=verifier_agent_id_in OR EXISTS (
      SELECT 1 FROM public.tasks p WHERE p.id=t.parent_task_id AND p.agent_id=verifier_agent_id_in
    ));
  IF NOT FOUND THEN RAISE EXCEPTION 'Task is not awaiting verification or verifier is not its orchestrator'; END IF;
  SELECT * INTO task_out FROM public.tasks WHERE id=task_id_in;
  INSERT INTO public.task_events(task_id,event_type,agent_id,message,payload)
  VALUES(task_id_in,CASE WHEN verified_in THEN 'verified' ELSE 'verification_rejected' END,
    verifier_agent_id_in,CASE WHEN verified_in THEN 'Result independently verified' ELSE 'Result rejected; task returned to queue' END,
    coalesce(verification_report_in,'{}'::jsonb));
  RETURN task_out;
END;
$$;

CREATE OR REPLACE FUNCTION public.task_ledger_children_summary(parent_task_id_in uuid)
RETURNS jsonb LANGUAGE sql STABLE SET search_path = public AS $$
  SELECT jsonb_build_object(
    'parent_task_id',parent_task_id_in,'total',count(*),
    'queued',count(*) FILTER (WHERE status='queued'),
    'running',count(*) FILTER (WHERE status='running'),
    'blocked',count(*) FILTER (WHERE status='blocked'),
    'waiting',count(*) FILTER (WHERE status='waiting'),
    'completed_unverified',count(*) FILTER (WHERE status='completed' AND verification_status<>'verified'),
    'verified',count(*) FILTER (WHERE status='completed' AND verification_status='verified'),
    'failed',count(*) FILTER (WHERE status='failed'),
    'cancelled',count(*) FILTER (WHERE status='cancelled'),
    'all_verified',coalesce(bool_and(status='completed' AND verification_status='verified'),true),
    'children',coalesce(jsonb_agg(jsonb_build_object('id',id,'task_key',task_key,'task_name',task_name,
      'status',status,'verification_status',verification_status,'claimed_by_agent_id',claimed_by_agent_id,
      'result_summary',result_summary) ORDER BY priority,started_at),'[]'::jsonb)
  ) FROM public.tasks WHERE parent_task_id=parent_task_id_in;
$$;

CREATE OR REPLACE FUNCTION public.task_ledger_finalize_parent(
  task_id_in uuid, verifier_agent_id_in text, outcome_in text, verification_report_in jsonb
) RETURNS public.tasks LANGUAGE plpgsql SET search_path = public AS $$
DECLARE task_out public.tasks;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.tasks WHERE id=task_id_in AND agent_id=verifier_agent_id_in) THEN
    RAISE EXCEPTION 'Only the parent task owner may finalize this task';
  END IF;
  IF EXISTS (SELECT 1 FROM public.tasks c WHERE c.parent_task_id=task_id_in
    AND NOT (c.status='completed' AND c.verification_status='verified')) THEN
    RAISE EXCEPTION 'Cannot finalize: one or more subtasks are not independently verified';
  END IF;
  UPDATE public.tasks SET status='completed',outcome=outcome_in,verification_status='verified',
    verification_report=coalesce(verification_report_in,'{}'::jsonb),
    verified_by_agent_id=verifier_agent_id_in,verified_at=now(),
    completed_at=now(),heartbeat_at=now(),updated_at=now()
  WHERE id=task_id_in RETURNING * INTO task_out;
  INSERT INTO public.task_events(task_id,event_type,agent_id,message,payload)
  VALUES(task_id_in,'completed',verifier_agent_id_in,outcome_in,
    jsonb_build_object('verification_report',coalesce(verification_report_in,'{}'::jsonb),
      'children_summary',public.task_ledger_children_summary(task_id_in)));
  RETURN task_out;
END;
$$;

CREATE OR REPLACE FUNCTION public.task_ledger_record_iteration(
  task_id_in uuid, agent_id_in text, claim_token_in uuid, iteration_no_in integer,
  input_payload_in jsonb DEFAULT '{}'::jsonb, output_payload_in jsonb DEFAULT '{}'::jsonb,
  observation_in jsonb DEFAULT '{}'::jsonb, decision_in text DEFAULT NULL,
  tools_used_in jsonb DEFAULT '[]'::jsonb, evidence_in jsonb DEFAULT '[]'::jsonb,
  status_in text DEFAULT 'completed'
) RETURNS public.task_iterations LANGUAGE plpgsql SET search_path = public AS $$
DECLARE iteration_out public.task_iterations;
BEGIN
  IF status_in NOT IN ('started','completed','failed','skipped') THEN RAISE EXCEPTION 'Invalid iteration status'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.tasks WHERE id=task_id_in AND claimed_by_agent_id=agent_id_in
    AND claim_token=claim_token_in AND status='running') THEN
    RAISE EXCEPTION 'Active task claim required to record an iteration';
  END IF;
  INSERT INTO public.task_iterations(task_id,iteration_no,agent_id,status,input_payload,output_payload,
    observation,decision,tools_used,evidence,completed_at)
  VALUES(task_id_in,iteration_no_in,agent_id_in,status_in,coalesce(input_payload_in,'{}'::jsonb),
    coalesce(output_payload_in,'{}'::jsonb),coalesce(observation_in,'{}'::jsonb),decision_in,
    coalesce(tools_used_in,'[]'::jsonb),coalesce(evidence_in,'[]'::jsonb),
    CASE WHEN status_in='started' THEN NULL ELSE now() END)
  RETURNING * INTO iteration_out;
  UPDATE public.tasks SET heartbeat_at=now(),updated_at=now() WHERE id=task_id_in;
  INSERT INTO public.task_events(task_id,event_type,agent_id,message,payload)
  VALUES(task_id_in,'iteration_recorded',agent_id_in,decision_in,
    jsonb_build_object('iteration_id',iteration_out.id,'iteration_no',iteration_no_in,'status',status_in));
  RETURN iteration_out;
END;
$$;

CREATE OR REPLACE VIEW public.task_hierarchy WITH (security_invoker=true) AS
WITH RECURSIVE task_tree AS (
  SELECT t.id,t.task_key,t.parent_task_id,t.task_name,t.status,t.verification_status,
    t.agent_id,t.claimed_by_agent_id,t.priority,0 AS depth,ARRAY[t.id] AS path
  FROM public.tasks t WHERE t.parent_task_id IS NULL
  UNION ALL
  SELECT c.id,c.task_key,c.parent_task_id,c.task_name,c.status,c.verification_status,
    c.agent_id,c.claimed_by_agent_id,c.priority,p.depth+1,p.path||c.id
  FROM public.tasks c JOIN task_tree p ON c.parent_task_id=p.id
  WHERE NOT c.id=ANY(p.path)
)
SELECT * FROM task_tree;

